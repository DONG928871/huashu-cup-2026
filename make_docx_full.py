def run(text, bold=False, sz=24, fn='宋体', italic=False):
    rpr = ('<w:b/>' if bold else '') + ('<w:i/>' if italic else '')
    rpr += f'<w:sz w:val="{sz}"/><w:rFonts w:ascii="{fn}" w:hAnsi="{fn}" w:eastAsia="{fn}"/>'
    return f'<w:r><w:rPr>{rpr}</w:rPr><w:t xml:space="preserve">{text}</w:t></w:r>'

def para(content, align='left', sa=120, sb=0, fl=0):
    ppr = '<w:pPr>'
    if align=='center': ppr+='<w:jc w:val="center"/>'
    elif align=='right': ppr+='<w:jc w:val="right"/>'
    ppr+=f'<w:spacing w:after="{sa}" w:before="{sb}"/>'
    if fl: ppr+=f'<w:ind w:firstLine="{fl}"/>'
    ppr+='</w:pPr>'
    return f'<w:p>{ppr}{content}</w:p>'

def tbl_row(cells, bold=False):
    tcs=''
    for c in cells:
        p=para(run(str(c),bold=bold,sz=20,fn='宋体'),align='center',sa=0)
        tcs+=f'<w:tc>{p}</w:tc>'
    return f'<w:tr>{tcs}</w:tr>'

def TABLE(headers, rows):
    tbl='<w:tblPr><w:tblStyle w:val="TableGrid"/><w:tblW w:w="9000" w:type="dxa"/></w:tblPr>'
    tbl+=tbl_row(headers,bold=True)
    for r in rows: tbl+=tbl_row([str(c) for c in r])
    return f'<w:tbl>{tbl}</w:tbl>'

